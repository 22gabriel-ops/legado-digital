test('native preparation raises app and pod minimums, preserves higher versions and is repeatable',t=>{
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'legado-native-'));
 t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
 fs.mkdirSync(path.join(root,'ios/App/App.xcodeproj'),{recursive:true});
 fs.mkdirSync(path.join(root,'ios/App/App'),{recursive:true});
 const project=path.join(root,'ios/App/App.xcodeproj/project.pbxproj'),podfile=path.join(root,'ios/App/Podfile'),plist=path.join(root,'ios/App/App/Info.plist');
 fs.writeFileSync(project,'developmentRegion = en;\nknownRegions = (en, Base,);\nIPHONEOS_DEPLOYMENT_TARGET = 14.0;\nIPHONEOS_DEPLOYMENT_TARGET = 17.0;');
 fs.writeFileSync(podfile,"platform :ios, '14.0'\npost_install do |installer|\n  assertDeploymentTarget(installer)\nend\n");
 fs.writeFileSync(plist,'<?xml version="1.0"?><plist><dict><key>CFBundleName</key><string>Legado</string><key>UIMainStoryboardFile</key><string>Main</string><key>UILaunchStoryboardName</key><string>LaunchScreen</string></dict></plist>');
 const originalDelegate=seedMainAndDelegate(root),delegate=path.join(root,'ios/App/App/AppDelegate.swift');
 const script=fileURLToPath(new URL('./prepare_apple_native.mjs',import.meta.url));
 execFileSync(process.execPath,[script],{cwd:root});
 assert.match(fs.readFileSync(project,'utf8'),/16\.0/);assert.match(fs.readFileSync(project,'utf8'),/17\.0/);
 assert.match(fs.readFileSync(project,'utf8'),/developmentRegion = "pt-BR";/);
 assert.match(fs.readFileSync(project,'utf8'),/knownRegions = \(\s*"pt-BR",\s*Base,/);
 assert.match(fs.readFileSync(plist,'utf8'),/<key>CFBundleDevelopmentRegion<\/key>\s*<string>pt-BR<\/string>/);
 assert.match(fs.readFileSync(plist,'utf8'),/<key>CFBundleLocalizations<\/key>\s*<array>\s*<string>pt-BR<\/string>\s*<\/array>/);
 const info=readPlist(plist),scene=info.UIApplicationSceneManifest;
 assert.equal(info.UIMainStoryboardFile,undefined);assert.equal(info.UILaunchStoryboardName,'LaunchScreen');
 assert.equal(scene.UIApplicationSupportsMultipleScenes,false);
 assert.deepEqual(Object.keys(scene.UISceneConfigurations),['UIWindowSceneSessionRoleApplication']);
 assert.equal(scene.UISceneConfigurations.UIWindowSceneSessionRoleApplication[0].UISceneStoryboardFile,'Main');
 const generated=fs.readFileSync(delegate,'utf8');
 const hook=generated.slice(generated.indexOf('    // BEGIN LEGADO SCENE CONFIGURATION'),generated.indexOf('    // END LEGADO SCENE CONFIGURATION'));
 assert.match(hook,/guard connectingSceneSession\.role == \.windowApplication else/);assert.match(hook,/UISceneConfiguration\(name: nil/);assert.match(hook,/ignored\.delegateClass = nil/);assert.match(hook,/ignored\.storyboard = nil/);
 const delegateScene=generated.slice(generated.indexOf('// BEGIN LEGADO SINGLE SCENE'));
 assert.doesNotMatch(delegateScene,/UIWindow\(|CAPBridgeViewController\(/);assert.doesNotMatch(delegateScene,/NotificationCenter|post\(/);
 assert.match(delegateScene,/guard session\.role == \.windowApplication/);assert.equal((delegateScene.match(/guard scene\.session\.role == \.windowApplication/g)||[]).length,2);
 for(const part of ['forwardURLs(connectionOptions.urlContexts)','connectionOptions.userActivities','context.options.sourceApplication','context.options.annotation','context.options.openInPlace','delegate.application(UIApplication.shared, open: context.url, options: options)','delegate.application(UIApplication.shared, continue: activity, restorationHandler:'])assert.ok(delegateScene.includes(part),part);
 const preserved=generated.replace(/\n\n    \/\/ BEGIN LEGADO SCENE CONFIGURATION[\s\S]*?    \/\/ END LEGADO SCENE CONFIGURATION/,'').split('// BEGIN LEGADO SINGLE SCENE')[0].trimEnd();
 assert.equal(preserved,originalDelegate.trimEnd());
 assert.match(fs.readFileSync(podfile,'utf8'),/installer.pods_project.targets.each/);
 assert.match(fs.readFileSync(podfile,'utf8'),/Gem::Version.new\(current\) < Gem::Version.new\('16.0'\)/);
 const first=[project,podfile,plist,delegate].map(p=>fs.readFileSync(p,'utf8'));
 execFileSync(process.execPath,[script],{cwd:root});
 assert.deepEqual([project,podfile,plist,delegate].map(p=>fs.readFileSync(p,'utf8')),first);
});
