function seedMainAndDelegate(root){
 const archive=fileURLToPath(new URL('../node_modules/@capacitor/cli/assets/ios-pods-template.tar.gz',import.meta.url));
 for(const name of ['AppDelegate.swift','Base.lproj/Main.storyboard']){
  const target=path.join(root,'ios/App/App',name);fs.mkdirSync(path.dirname(target),{recursive:true});
  fs.writeFileSync(target,execFileSync('/usr/bin/tar',['-xOf',archive,'App/App/'+name]));
 }
 return fs.readFileSync(path.join(root,'ios/App/App/AppDelegate.swift'),'utf8');
}
