import {PGlite} from 'npm:@electric-sql/pglite@0.3.14';
import assert from 'node:assert/strict';
Deno.test('SQL preserves Sandbox isolation, real quota, event ordering, ownership and rollback',async()=>{
const db=new PGlite();
try{
await db.exec(`CREATE SCHEMA auth; CREATE TABLE auth.users(id uuid PRIMARY KEY); CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;
CREATE FUNCTION auth.role() RETURNS text LANGUAGE sql AS $$ SELECT current_setting('test.role',true) $$;
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql AS $$ SELECT nullif(current_setting('test.uid',true),'')::uuid $$;
CREATE TABLE legacy_user_entitlements(owner_id uuid PRIMARY KEY REFERENCES auth.users(id),plan text NOT NULL CHECK(plan IN ('essential','complete')),active_until timestamptz,updated_at timestamptz DEFAULT now());
SET test.role='service_role';
INSERT INTO auth.users VALUES('11111111-1111-4111-8111-111111111111'),('22222222-2222-4222-8222-222222222222');`);
const base=new URL('../supabase/migrations/',import.meta.url);
const readMigration=name=>Deno.readTextFile(new URL(name,base));
const monthly=await readMigration('20261014_monthly_credits.sql');
await db.exec(monthly.slice(0,monthly.indexOf('-- Charge one completed')));
await db.exec(await readMigration('20261103_apple_billing.sql'));
const owner='11111111-1111-4111-8111-111111111111';
const future=new Date(Date.now()+86400000).toISOString();
const row={owner_id:owner,original_transaction_id:'10001',transaction_id:'10002',environment:'Sandbox',product_id:'br.com.meulegado.plus.mensal',active_until:future,active:true,signed_at:new Date().toISOString()};
const apply=async(s)=>db.query('SELECT legacy_apply_apple_subscription($1::jsonb)',[JSON.stringify(s)]);
await apply(row);
await db.exec("GRANT USAGE ON SCHEMA auth TO authenticated; SET ROLE authenticated;");
await db.query("SELECT set_config('test.uid',$1,false)",['22222222-2222-4222-8222-222222222222']);
let visible=await db.query('SELECT * FROM legacy_apple_subscriptions');
assert.equal(visible.rows.length,0,'RLS must hide another account subscription');
await db.query("SELECT set_config('test.uid',$1,false)",[owner]);
visible=await db.query('SELECT * FROM legacy_apple_subscriptions');
assert.equal(visible.rows.length,1,'The app can read its own subscription');
await assert.rejects(()=>db.query('DELETE FROM legacy_apple_subscriptions'));
await db.exec('RESET ROLE');
let result=await db.query('SELECT * FROM legacy_reserve_interaction($1,$2)',[owner,'message-one']);
assert.equal(result.rows[0].allowance,10,'Sandbox must not upgrade production quota');
await apply({...row,environment:'Production'});
result=await db.query('SELECT * FROM legacy_reserve_interaction($1,$2)',[owner,'message-two']);
assert.equal(result.rows[0].allowance,100);
assert.equal(result.rows[0].used_count,2);
await apply({...row,environment:'Production'});
result=await db.query('SELECT * FROM legacy_reserve_interaction($1,$2)',[owner,'message-two']);
assert.equal(result.rows[0].used_count,2,'Duplicate message must not double-charge quota');
await assert.rejects(()=>apply({...row,environment:'Production',owner_id:'22222222-2222-4222-8222-222222222222'}));
await apply({...row,environment:'Production',active:false,signed_at:new Date(Date.now()+1000).toISOString()});
await apply({...row,environment:'Production',active:true,signed_at:new Date(Date.now()-1000).toISOString()});
result=await db.query('SELECT * FROM legacy_reserve_interaction($1,$2)',[owner,'message-three']);
assert.equal(result.rows[0].allowance,10,'Revoked subscription cannot be restored by an older event');
await db.exec("SET test.role='authenticated'");
await assert.rejects(()=>apply(row));
await db.exec("SET test.role='service_role'");
await db.exec(await Deno.readTextFile(new URL('../supabase/rollback/20261103_apple_billing.sql',import.meta.url)));
result=await db.query('SELECT * FROM legacy_reserve_interaction($1,$2)',[owner,'message-after-rollback']);
assert.equal(result.rows[0].allowance,10);
const history=await db.query('SELECT count(*)::int AS count FROM legacy_apple_subscriptions');
assert.equal(history.rows[0].count,2,'Rollback must preserve subscription history');
}finally{await db.close()}
});
